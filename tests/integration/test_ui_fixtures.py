"""The UI's test fixtures are real API answers (D84), generated here.

The demo inbox (gold client, no model) is filled into the emptied commit-test database
under a fixed clock; one draft is approved and one rejected through the API, so the
inbox shows several statuses; then the answers the UI's tests use are fetched through
a logged-in client and rendered as TypeScript modules, `export default <json> satisfies
<Type>;`. `satisfies` makes tsc check every fixture against the UI's response type: a
field the API dropped, or one the UI does not know, fails the web job's typecheck.

Check mode (default, CI): every file must exist and match what the API answers now,
and no other file may be in the folder. Write mode, after an API change:

    ANEMOS_WRITE_FIXTURES=1 uv run --env-file .env pytest tests/integration/test_ui_fixtures.py

Only response bodies are written, never headers. A fixture that contains the
password, a session token, the cookie name or a Set-Cookie fails the test, in both
modes, before anything is written.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterator
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import TYPE_CHECKING, Any

import pytest
from fastapi.testclient import TestClient

from anemos.api import create_app
from anemos.api.auth import COOKIE_NAME, OwnerAuth
from anemos.api.security import CLIENT_HEADER, CLIENT_VALUE
from anemos.clock import FixedClock
from anemos.demo_inbox import fill

if TYPE_CHECKING:  # tests/ is not a package: the fixture's class is for mypy only
    from conftest import CommittedDb

pytestmark = pytest.mark.integration

FIXTURES = Path(__file__).resolve().parents[2] / "web" / "src" / "test" / "fixtures"
WRITE = os.environ.get("ANEMOS_WRITE_FIXTURES") == "1"
AT = datetime(2027, 3, 1, 9, 0, tzinfo=UTC)
LATER = AT + timedelta(hours=73)  # every pending draft is past 72 h (D42, D54)
PASSWORD = "fixture-generator-password"  # fictional; the secret check looks for it
APPROVED = "Sea view room in June"  # a quote with a hold: answered
REJECTED = "November break"  # a decline: closed
EDITED = "Family stay"  # an ask_info the owner edits: two versions
OWNER_LINE = "\n\nP.S. We look forward to welcoming you."  # by the owner: no digits
DETAILS = {  # fixture name: subject
    "detailGroup.ts": "Δωμάτια για βάπτιση",  # escalated by code, summary adds DISCOUNT
    "detailComplaint.ts": "Noise during our stay",  # escalated by the agent
    "detailQuote.ts": "Two rooms in August",  # pending quote with an offer
    "detailEdited.ts": EDITED,
    "detailAnswered.ts": APPROVED,  # approved: hold and outbox
    "detailSetAside.ts": "You have won a free cruise",
}

HEADER = (
    "// Generated by tests/integration/test_ui_fixtures.py from the real API (D84).\n"
    "// Do not edit. After an API change: ANEMOS_WRITE_FIXTURES=1 uv run --env-file .env\n"
    "// pytest tests/integration/test_ui_fixtures.py\n"
)


def render(type_name: str, body: Any) -> str:
    text = json.dumps(body, indent=2, ensure_ascii=False)
    return (
        f'{HEADER}import type {{ {type_name} }} from "../../types";\n\n'
        f"export default {text} satisfies {type_name};\n"
    )


def secrets_in(text: str, tokens: list[str]) -> list[str]:
    """Which secrets a fixture text contains (case-insensitive for the names)."""
    lower = text.lower()
    found = [name for name in (PASSWORD, COOKIE_NAME, "set-cookie") if name.lower() in lower]
    return found + [f"token {t[:6]}…" for t in tokens if t in text]


@pytest.fixture
def client(committed_db: CommittedDb) -> Iterator[Any]:
    """client(at): logged in through the real POST /api/session; tokens collected."""
    opened: list[TestClient] = []

    def make(at: datetime) -> TestClient:
        app = create_app(committed_db.connect, FixedClock(at), OwnerAuth(PASSWORD))
        api = TestClient(app, base_url="https://testserver",
                         headers={CLIENT_HEADER: CLIENT_VALUE})  # fmt: skip
        opened.append(api)
        assert api.post("/api/session", json={"password": PASSWORD}).status_code == 204
        return api

    yield make
    for api in opened:
        api.close()


def generate(committed_db: CommittedDb, client: Any) -> tuple[dict[str, str], list[str]]:
    """{file name: text} and the session tokens used."""
    fill(committed_db.connect, FixedClock(AT))
    api, later = client(AT), client(LATER)

    def ok(response: Any) -> Any:
        assert response.status_code == 200, response.text
        return response.json()

    by_subject = {e["subject"]: e for e in ok(api.get("/api/emails"))["items"]}
    ok(api.post(f"/api/drafts/{by_subject[APPROVED]['draft_id']}/approve", json={"version": 1}))
    ok(api.post(f"/api/drafts/{by_subject[REJECTED]['draft_id']}/reject"))
    edited = ok(api.get(f"/api/emails/{by_subject[EDITED]['id']}"))["draft"]
    body = edited["versions"][0]["body"] + OWNER_LINE
    response = api.post(f"/api/drafts/{edited['id']}/versions",
                        json={"body": body, "base_version": 1})  # fmt: skip
    assert response.status_code == 201, response.text
    assert response.json()["warnings"] == []  # a clean edit: no price or guardrail warning

    first = ok(api.get("/api/emails", params={"limit": 4}))
    files = {
        "inbox.ts": render("EmailPage", ok(api.get("/api/emails"))),
        "inboxSetAside.ts": render(
            "EmailPage", ok(api.get("/api/emails", params={"status": "set_aside"}))
        ),
        "inboxPage1.ts": render("EmailPage", first),
        "inboxPage2.ts": render(
            "EmailPage",
            ok(api.get("/api/emails", params={"limit": 4, "cursor": first["next_cursor"]})),
        ),
        "inboxLater.ts": render("EmailPage", ok(later.get("/api/emails"))),
    }
    spam = ok(api.get("/api/emails", params={"status": "set_aside"}))["items"]
    ids = {e["subject"]: e["id"] for e in [*ok(api.get("/api/emails"))["items"], *spam]}
    for name, subject in DETAILS.items():
        files[name] = render("EmailDetail", ok(api.get(f"/api/emails/{ids[subject]}")))
    tokens = [token for c in (api, later) if (token := c.cookies.get(COOKIE_NAME))]
    return files, tokens


def test_the_ui_fixtures_are_the_api_s_current_answers(
    committed_db: CommittedDb, client: Any
) -> None:
    files, tokens = generate(committed_db, client)
    assert len(tokens) == 2
    leaks = {name: found for name, text in files.items() if (found := secrets_in(text, tokens))}
    assert leaks == {}, "a fixture would contain a secret; nothing written"

    if WRITE:
        FIXTURES.mkdir(parents=True, exist_ok=True)
        for old in FIXTURES.glob("*.ts"):
            old.unlink()
        for name, text in files.items():
            (FIXTURES / name).write_text(text, encoding="utf-8", newline="\n")
        return
    on_disk = {p.name: p.read_text(encoding="utf-8") for p in FIXTURES.glob("*.ts")}
    stale = sorted(n for n in files.keys() | on_disk.keys() if files.get(n) != on_disk.get(n))
    assert stale == [], (
        f"UI fixtures differ from the API's answers: {stale}. Regenerate with "
        "ANEMOS_WRITE_FIXTURES=1 uv run --env-file .env pytest "
        "tests/integration/test_ui_fixtures.py"
    )


@pytest.mark.parametrize("name", sorted(p.name for p in FIXTURES.glob("*.ts")) or ["none"])
def test_no_fixture_file_holds_a_secret(name: str) -> None:
    """Also catches a hand edit: the password, the cookie name, a Set-Cookie."""
    assert name != "none", "no UI fixtures found; generate them (module docstring)"
    assert secrets_in((FIXTURES / name).read_text(encoding="utf-8"), []) == []


@pytest.mark.parametrize(
    ("text", "found"),
    [
        ('{"subject": "fixture-generator-password"}', [PASSWORD]),
        ('{"x": "Set-Cookie: anemos_session=abc"}', [COOKIE_NAME, "set-cookie"]),
        ('{"x": "tok-123456789"}', ["token tok-12…"]),
        ('{"subject": "Sea view room in June"}', []),
    ],
)
def test_the_secret_check_finds_each_kind(text: str, found: list[str]) -> None:
    assert secrets_in(text, ["tok-123456789"]) == found
